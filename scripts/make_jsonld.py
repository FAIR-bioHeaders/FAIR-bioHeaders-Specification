"""Generate the FHR JSON-LD context and vocabulary from the LinkML model.

The LinkML annotations in ``schemas/core.yaml`` and ``fhr_linkml.yml`` are the
single source of the term IRIs (specs/011-jsonld-mapping research R-08). This
script writes:

- ``jsonld/fhr.context.jsonld``: the JSON-LD 1.1 context, with a
  property-scoped context for every nested FHR object (data-model sections 1-2);
- ``jsonld/terms.ttl``, ``jsonld/terms.jsonld`` and ``docs/TERMS.md``: the
  FAIR-bioHeaders vocabulary as Turtle, as JSON-LD and as a documentation page
  (contracts/vocabulary.md);
- ``examples/example.fhr.jsonld`` and ``examples/minimal.fhr.jsonld``: the
  reference writer's output for the JSON examples (rule J7);
- ``examples/example.fhr.export.jsonld`` and ``tests/fixtures/schemaorg-export/*/expected.jsonld``:
  the one-way schema.org export profile (specs/013-schemaorg-export, ``to_export``);
- the summary table in ``docs/MAPPINGS.md`` and the DCMI line of each term in
  ``docs/TERMS.md``, from the curated ``mappings/fhr-jsonld-dcmi.yml``.

It is also the reference JSON-LD writer (``to_jsonld``, contracts/cli.md
"Writing") and canonical reader (``canonical_record``, rule J1) that the tests,
the conformance vectors and docs/JSONLD.md follow. These need only the standard
library; generating the context needs LinkML.

``--check`` regenerates everything in memory and exits 1 with a unified diff if
a committed file differs; ``--examples`` writes only the JSON-LD examples;
``--mappings-summary`` prints the mapping summary table. The script never uses
the network.
"""

