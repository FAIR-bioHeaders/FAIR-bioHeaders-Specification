def annotations(element):
    """Return an element's LinkML annotations as a plain dict."""
    found = element.annotations
    if not found:
        return {}
    if hasattr(found, "items"):
        return {tag: value.value for tag, value in found.items()}
    from jsonasobj2 import as_dict

    return {tag: value["value"] if isinstance(value, dict) else value
            for tag, value in as_dict(found).items()}


def compact(iri):
    for prefix, namespace in (("sdo", SDO), ("fhr", FHR), ("dct", DCT), ("xsd", XSD)):
        if iri.startswith(namespace):
            return f"{prefix}:{iri[len(namespace):]}"
    return iri


def local_name(curie):
    return curie.split(":", 1)[1]


class Model:
    """The LinkML classes reachable from FHR, with keys in fhr.json order."""

    def __init__(self):
        from linkml_runtime import SchemaView

        self.view = SchemaView(str(LINKML))
        self.schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
        if self.view.schema.default_prefix != "fhr":
            raise ValueError("fhr_linkml.yml must set default_prefix: fhr")

    def resolve(self, node):
        while "$ref" in node:
            target = self.schema
            for part in node["$ref"][2:].split("/"):
                target = target[part]
            node = {**target, **{k: v for k, v in node.items() if k != "$ref"}}
        return node

    def object_node(self, node):
        """The fhr.json object schema under ``node`` (through items and anyOf)."""
        node = self.resolve(node)
        if "properties" in node:
            return node
        if "items" in node:
            return self.object_node(node["items"])
        for option in node.get("anyOf", []):
            found = self.object_node(option)
            if found is not None:
                return found
        return None

    def slots(self, class_name, node):
        """Induced slots of ``class_name`` in the property order of ``node``."""
        induced = {slot.name: slot for slot in self.view.class_induced_slots(class_name)}
        order = list(node["properties"])
        if set(order) != set(induced):
            raise ValueError(f"{class_name}: LinkML slots {sorted(induced)} differ from "
                             f"fhr.json properties {sorted(order)}")
        return [induced[name] for name in order]

    def class_range(self, slot):
        """The class a slot holds (inlined), or None."""
        ranges = [slot.range] + [option.range for option in slot.any_of or []]
        classes = [name for name in ranges if name and self.view.get_class(name) is not None]
        return classes[0] if classes else None

    def multivalued(self, slot):
        return bool(slot.multivalued) or any(o.multivalued for o in slot.any_of or [])

    def iri(self, slot):
        return self.view.get_uri(slot, expand=True)

    def class_iri(self, class_name):
        return self.view.get_uri(self.view.get_class(class_name), expand=True)

    def walk(self, class_name=ROOT_CLASS, node=None, seen=None):
        """Yield ``(class_name, fhr.json node, slots)`` for every reachable class."""
        node = self.schema if node is None else node
        seen = set() if seen is None else seen
        if class_name in seen:
            return
        seen.add(class_name)
        slots = self.slots(class_name, node)
        yield class_name, node, slots
        for slot in slots:
            child = self.class_range(slot)
            if child:
                yield from self.walk(child, self.object_node(node["properties"][slot.name]),
                                     seen)


def type_terms(model, class_name):
    """The type terms the writer can emit on nodes of ``class_name``."""
    cls = model.view.get_class(class_name)
    terms = {}
    extra = annotations(cls)
    for tag in ("jsonld_type_if_orcid", "jsonld_type_if_ror"):
        if tag in extra:
            terms[local_name(extra[tag])] = extra[tag]
    class_curie = compact(model.class_iri(class_name))
    terms[local_name(class_curie)] = class_curie
    return terms


def term_definition(model, slot, node):
    if annotations(slot).get("jsonld_node_id") is True:
        return "@id"
    definition = {"@id": compact(model.iri(slot))}
    child = model.class_range(slot)
    if slot.range == "uri" or annotations(slot).get("jsonld_iri") is True:
        definition["@type"] = "@id"
    elif slot.range == "date":
        definition["@type"] = "xsd:date"
    if model.multivalued(slot):
        definition["@container"] = "@list" if slot.list_elements_ordered else "@set"
    if child:
        definition["@context"] = [None, scope(model, child, model.object_node(node))]
    return definition


def scope(model, class_name, node):
    """The property-scoped context body for nodes of ``class_name``."""
    body = {"@protected": True, **PREFIXES, **type_terms(model, class_name)}
    for slot in model.slots(class_name, node):
        body[slot.name] = term_definition(model, slot, node["properties"][slot.name])
    check_injective(class_name, body)
    return body


def expand(value, prefixes):
    value = value["@id"] if isinstance(value, dict) else value
    if value.startswith("@") or "://" in value:
        return value
    prefix, _, rest = value.partition(":")
    return prefixes[prefix] + rest


def check_injective(name, body):
    """Fail if two keys of one scope map to the same IRI (data-model rule 4)."""
    prefixes = {**PREFIXES, "xsd": XSD, "dct": DCT}
    seen = {}
    for key, value in body.items():
        if key.startswith("@") or key in prefixes:
            continue
        iri = expand(value, prefixes)
        if iri in seen:
            raise ValueError(f"scope {name}: {seen[iri]} and {key} both map to {iri}")
        seen[iri] = key


def build_context(model):
    root = {"@version": 1.1, "@protected": True, **PREFIXES, "xsd": XSD, "dct": DCT}
    root.update(type_terms(model, ROOT_CLASS))
    # The nested node types are defined in their property-scoped contexts, a
    # JSON-LD 1.1 feature. Defining them at the root as well lets 1.0-only
    # tools, such as validator.schema.org, recognise the types (quickstart V8);
    # 1.1 processors use the scoped definitions, which are the same IRIs.
    for class_name, _, _ in model.walk():
        if class_name != ROOT_CLASS:
            root.update(type_terms(model, class_name))
    url_terms = {}
    for slot in model.slots(ROOT_CLASS, model.schema):
        root[slot.name] = term_definition(model, slot, model.schema["properties"][slot.name])
        alternative = annotations(slot).get("jsonld_slot_uri_if_url")
        if alternative:
            url_terms[local_name(alternative)] = {"@id": alternative, "@type": "@id"}
    root.update(url_terms)
    root.update(EXPORT_TERMS)
    check_injective(ROOT_CLASS, root)
    return {"@context": root}


