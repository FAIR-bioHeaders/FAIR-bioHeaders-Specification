def is_export(document):
    """True for a document written with the export profile (research R-11)."""
    return isinstance(document, dict) and document.get("@context") == EXPORT_CONTEXT


def scope_terms(context=None):
    """Property terms of the nested scopes whose objects FHR leaves open."""
    root = (load_context() if context is None else context)["@context"]
    terms = {}
    for key in ("taxon", *AUTHOR_KEYS, "accessionID", "vitalStats"):
        body = root[key]["@context"][1]
        terms[key] = {term for term, value in body.items()
                      if isinstance(value, dict) or value == "@id"}
    return terms


def unmapped_keys(record, context=None):
    """Paths of nested keys that have no term in their scope (research R-07)."""
    terms = scope_terms(context)
    found = []
    for key, value in record.items():
        if key not in terms:
            continue
        if isinstance(value, dict):
            items = [(key, value)]
        elif isinstance(value, list):
            items = [(f"{key}[{index}]", item) for index, item in enumerate(value)
                     if isinstance(item, dict)]
        else:
            items = []
        for path, item in items:
            found += [f"{path}.{name}" for name in item if name not in terms[key]]
    return found


def is_canonical(document, context=None):
    """Rule J1: a bundled context, and no keyword but @type (and a root @id)."""
    if not isinstance(document, dict) or "@context" not in document:
        return False
    bundled = (load_context() if context is None else context)["@context"]
    value = document["@context"]
    if not (value == bundled or (isinstance(value, str) and value in KNOWN_CONTEXT_URLS)):
        return False
    if "@id" in document and not isinstance(document["@id"], str):
        return False

    def plain(node, root):
        if isinstance(node, list):
            return all(plain(item, False) for item in node)
        if not isinstance(node, dict):
            return True
        for key, item in node.items():
            if key == "@type":
                if not (isinstance(item, str)
                        or isinstance(item, list) and all(isinstance(t, str) for t in item)):
                    return False
            elif key.startswith("@"):
                if not (root and key in ("@context", "@id")):
                    return False
            elif not plain(item, False):
                return False
        return True

    return plain(document, True)


def _without_types(value):
    if isinstance(value, dict):
        return {key: _without_types(item) for key, item in value.items() if key != "@type"}
    if isinstance(value, list):
        return [_without_types(item) for item in value]
    return value


def canonical_record(document, warn=None, context=None):
    """Rule J1: set @context and @type aside; restore documentation; drop export terms."""
    if is_export(document):
        raise ValueError(EXPORT_REFUSAL)
    if not is_canonical(document, context):
        raise ValueError(NOT_CANONICAL)
    record = {}
    for key, value in document.items():
        if key in ("@context", "@type"):
            continue
        if key in EXPORT_OUTPUT:
            if warn is not None:
                warn(f"JSON-LD: {key} is export metadata, not an FHR field; it was not kept")
            continue
        if key == URL_TERM:
            if "documentation" in document:
                raise ValueError("JSON-LD gives both documentation and subjectOf")
            if not isinstance(value, str):
                raise ValueError("JSON-LD subjectOf must be a string")
            key = "documentation"
        record[key] = _without_types(value)
    return record


