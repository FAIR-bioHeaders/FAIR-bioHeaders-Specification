def build_turtle(classes, properties):
    blocks = [TURTLE_HEADER]
    for name in ordered(classes):
        entry = classes[name]
        lines = [f"fhr:{name} a rdfs:Class ;",
                 f"    rdfs:label {turtle_string(name)} ;",
                 f"    rdfs:comment {turtle_string(entry['comment'])} ;"]
        if entry["subClassOf"]:
            lines.append(f"    rdfs:subClassOf {', '.join(entry['subClassOf'])} ;")
        if entry["closeMatch"]:
            lines.append(f"    skos:closeMatch {', '.join(entry['closeMatch'])} ;")
        lines.append(f"    rdfs:isDefinedBy <{VOCABULARY}> .")
        blocks.append("\n".join(lines) + "\n")
    for name in ordered(properties):
        entry = properties[name]
        lines = [f"fhr:{name} a rdf:Property ;",
                 f"    rdfs:label {turtle_string(name)} ;",
                 f"    rdfs:comment {turtle_string(entry['comment'])} ;",
                 f"    sdo:domainIncludes {', '.join(entry['domain'])} ;",
                 f"    sdo:rangeIncludes {', '.join(entry['range'])} ;"]
        if entry["subPropertyOf"]:
            lines.append(f"    rdfs:subPropertyOf {', '.join(entry['subPropertyOf'])} ;")
        lines.append(f"    rdfs:isDefinedBy <{VOCABULARY}> .")
        blocks.append("\n".join(lines) + "\n")
    return "\n".join(blocks)


